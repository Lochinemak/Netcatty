//! Recorded steps → JavaScript (`electron/scripts/scriptCodegen.cjs`).

use serde_json::Value;

const HEADER: &str = "// Auto-generated by Netcatty Script Recorder";

/// `JSON.stringify(String(value ?? ""))`.
fn escape_js_string(value: Option<&Value>) -> String {
    let text = match value {
        None | Some(Value::Null) => String::new(),
        Some(v) => crate::dialog::js_string(v),
    };
    serde_json::to_string(&text).unwrap_or_else(|_| "\"\"".into())
}

fn step_number(value: Option<&Value>, fallback: i64) -> i64 {
    match value.and_then(crate::dialog::js_number) {
        Some(n) if n.is_finite() && n != 0.0 => n.trunc() as i64,
        _ => fallback,
    }
}

/// `stepsToJavaScript`: `async function main() { ... }` followed by
/// `await main();`. Sensitive sends become a masked prompt + sendLine.
pub fn steps_to_javascript(steps: &[Value], recorded_at: Option<&str>) -> String {
    let mut lines: Vec<String> = vec![HEADER.to_string()];
    if let Some(at) = recorded_at.filter(|s| !s.is_empty()) {
        lines.push(format!("// Recorded on {at}"));
    }
    lines.push(String::new());
    lines.push("async function main() {".into());

    for (index, step) in steps.iter().enumerate() {
        let step_type = step.get("type").and_then(|t| t.as_str()).unwrap_or("");
        match step_type {
            "send" => {
                if step.get("sensitive").is_some_and(crate::dialog::js_truthy) {
                    lines.push(format!(
                        "  const sensitiveValue{index} = await nct.dialog.prompt(\"Enter sensitive value\", \"\", {{ sensitive: true }});"
                    ));
                    lines.push(format!(
                        "  await nct.screen.sendLine(sensitiveValue{index}, {{ sensitive: true }});"
                    ));
                    continue;
                }
                lines.push(format!(
                    "  await nct.screen.sendLine({});",
                    escape_js_string(step.get("value"))
                ));
            }
            "waitFor" => lines.push(format!(
                "  await nct.screen.waitForText({}, {});",
                escape_js_string(step.get("value")),
                step_number(step.get("timeoutMs"), 5000)
            )),
            "waitForPrompt" => lines.push(format!(
                "  await nct.screen.waitForPrompt({});",
                step_number(step.get("timeoutMs"), 30000)
            )),
            "sleep" => lines.push(format!(
                "  await nct.session.sleep({});",
                step_number(step.get("value"), 1000)
            )),
            _ => {}
        }
    }

    lines.push("}".into());
    lines.push(String::new());
    lines.push("await main();".into());
    lines.join("\n")
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn sends_sensitive_prompt_result() {
        let code = steps_to_javascript(&[json!({ "type": "send", "value": "secret", "sensitive": true })], None);
        assert!(code.contains("const sensitiveValue0 = await nct.dialog.prompt(\"Enter sensitive value\", \"\", { sensitive: true });"));
        assert!(code.contains("await nct.screen.sendLine(sensitiveValue0, { sensitive: true });"));
        assert!(!code.contains("secret"));
    }

    #[test]
    fn generates_send_line_and_wait_for_prompt_steps() {
        let code = steps_to_javascript(
            &[
                json!({ "type": "send", "value": "ls -la" }),
                json!({ "type": "waitForPrompt", "timeoutMs": 5000 }),
                json!({ "type": "waitFor", "value": "done" }),
                json!({ "type": "sleep", "value": 250 }),
            ],
            Some("2026-01-01T00:00:00.000Z"),
        );
        assert_eq!(
            code,
            [
                "// Auto-generated by Netcatty Script Recorder",
                "// Recorded on 2026-01-01T00:00:00.000Z",
                "",
                "async function main() {",
                "  await nct.screen.sendLine(\"ls -la\");",
                "  await nct.screen.waitForPrompt(5000);",
                "  await nct.screen.waitForText(\"done\", 5000);",
                "  await nct.session.sleep(250);",
                "}",
                "",
                "await main();",
            ]
            .join("\n")
        );
    }
}
